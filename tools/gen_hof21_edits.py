# usage: gen_hof21_edits.py <GOG original H5_Game.exe> <Python-patched H5_Game.exe> <out .inc>
import sys
from pathlib import Path

import capstone
import pefile

IMAGE_REL_BASED_HIGHLOW = 3
GROUPS = {
    "kWidescreenEdits": [(0xE437E0, 0xE43D7C), (0xE3B2AB, 0xE3B2AD)],
    "kMinimapEdits": [(va, va + 8) for va in (0x833465, 0x83347B, 0x833522, 0x83353A, 0x8335DF,
                                               0x8335F7, 0x833796, 0x8337A9, 0x833962, 0x833975)],
}


def main(original_path: str, patched_path: str, out_path: str) -> None:
    original = pefile.PE(original_path)
    patched = pefile.PE(patched_path, fast_load=True)
    image_base = original.OPTIONAL_HEADER.ImageBase
    relocs = {block.struct.VirtualAddress + (e.struct.Data & 0xFFF)
              for block in original.DIRECTORY_ENTRY_BASERELOC for e in block.entries
              if e.type == IMAGE_REL_BASED_HIGHLOW}
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)

    lines = ["// Generated by tools/gen_hof21_edits.py; do not edit.", ""]
    for name, ranges in GROUPS.items():
        lines.append(f"constexpr ByteEdit {name}[] = {{")
        count = 0
        for start, end in ranges:
            code = original.get_data(start - image_base, end - start)
            for ins in md.disasm(code, start):
                old = bytes(ins.bytes)
                new = patched.get_data(ins.address - image_base, ins.size)
                if old == new:
                    continue
                abs_at = [r - (ins.address - image_base) for r in relocs if 0 <= r - (ins.address - image_base) < ins.size]
                if len(abs_at) > 1:
                    raise RuntimeError(f"{ins.address:#x}: more than one relocated operand")
                as_c = lambda b: "{" + ", ".join(f"0x{x:02X}" for x in b) + "}"
                lines.append(f"    {{0x{ins.address:X}, {ins.size}, {as_c(old)}, {as_c(new)}, "
                             f"{abs_at[0] if abs_at else -1}}},  // {ins.mnemonic} {ins.op_str}")
                count += 1
        if count == 0:
            raise RuntimeError(f"{name}: no edits found")
        lines.append("};")
        lines.append("")
        print(f"{name}: {count} edits")
    Path(out_path).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main(*sys.argv[1:])
